/**
 * Regenerate the HIGH_CONF block in play/index.html from the calibrated
 * high-profile weights files and the measured prices.
 *
 * The page carries its own copy of the strip weights and pay scales because it
 * must run with no build step. A copy kept by hand is a copy that drifts -- the
 * low profile's ROW_MULT_CAP sat at 60 in the page against 25 in the Rust while
 * every other check passed -- so the high profile's copy is generated:
 *
 *   packages/engine/src/paytables/weights/high/<id>.weights   (mathsim calibrate)
 *   packages/engine/src/paytables/weights/high/prices.json    (mathsim buyprice / ante)
 *
 *   node tools/high-conf.mjs          rewrite the block
 *   node tools/high-conf.mjs --check  exit 1 if the page is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "packages", "engine", "src", "paytables", "weights", "high");
const page = join(root, "play", "index.html");
const IDS = ["pride-high", "cubcluster-high", "traitvault-high"];
// Mirrors GameKind::max_win() in crates/mathsim/src/sim.rs; verify-play-math
// asserts the page enforces exactly these.
const CAP = { "pride-high": 5000, "cubcluster-high": 5000, "traitvault-high": 10000 };

function parseWeights(id) {
  const body = readFileSync(join(dir, `${id}.weights`), "utf8");
  let scale = null, coin = null, anteMult = 1, anteExtra = 1; const w = [];
  for (const raw of body.split("\n")) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const [key, ...rest] = line.split(/\s+/);
    if (key === "pay_scale") scale = +rest[0];
    else if (key === "coin_probability") coin = +rest[0];
    else if (key === "reel") w.push(rest.map(Number));
    else if (key === "ante_mult") anteMult = +rest[0];
    else if (key === "ante_extra") anteExtra = +rest[0];
  }
  if (scale === null || !w.length || w.some((r) => r.length !== 14))
    throw new Error(`malformed ${id}.weights`);
  return { scale, coin, w, anteMult, anteExtra };
}

const prices = JSON.parse(readFileSync(join(dir, "prices.json"), "utf8"));
const conf = [], buy = [], ante = [], verified = [];
for (const id of IDS) {
  const { scale, coin, w, anteMult, anteExtra } = parseWeights(id);
  const p = prices[id];
  if (!p || typeof p.buy !== "number" || !p.ante) throw new Error(`prices.json lacks ${id}`);
  const rows = w.map((r) => `[${r.join(",")}]`).join(",\n       ");
  conf.push(`  "${id}":{scale:${scale},cap:${CAP[id]}${id === "traitvault-high" ? `,orbP:${coin}` : ""},\n     w:[${rows}]}`);
  buy.push(`"${id}":${p.buy}`);
  // The ante's DEFINITION comes from the weights file; only its stake is a
  // measured price.
  ante.push(`"${id}":{mult:${anteMult},extraScatter:${anteExtra},stake:${p.ante.stake}}`);
  // Only a production-rng verification may be quoted; until one is recorded
  // the page says so rather than showing the calibration target.
  if (p.verified) verified.push(`"${id}":${JSON.stringify(p.verified)}`);
}
const block =
  "/* @@@HIGH_CONF@@@ */\n" +
  "// GENERATED by tools/high-conf.mjs from weights/high/*.weights and prices.json.\n" +
  `const HIGH_CONF={\n${conf.join(",\n")}\n};\n` +
  `const HIGH_BUY={${buy.join(",")}};\n` +
  `const HIGH_ANTE={${ante.join(",")}};\n` +
  `const HIGH_VERIFIED={${verified.join(",")}};\n` +
  "/* @@@HIGH_CONF_END@@@ */";

const html = readFileSync(page, "utf8");
const a = html.indexOf("/* @@@HIGH_CONF@@@ */"), b = html.indexOf("/* @@@HIGH_CONF_END@@@ */");
if (a < 0 || b < 0) { console.error("HIGH_CONF markers missing from play/index.html"); process.exit(2); }
const next = html.slice(0, a) + block + html.slice(b + "/* @@@HIGH_CONF_END@@@ */".length);
if (process.argv.includes("--check")) {
  if (next !== html) { console.error("play/index.html HIGH_CONF is stale: run node tools/high-conf.mjs"); process.exit(1); }
  console.log("HIGH_CONF matches the calibrated weights");
} else {
  writeFileSync(page, next);
  console.log(`HIGH_CONF regenerated for ${IDS.join(", ")}`);
}
