//! SHA-256 and HMAC-SHA256, no dependencies.
//!
//! Consensus-critical: the TypeScript engine derives outcomes with
//! node:crypto's HMAC-SHA256, and this must agree byte-for-byte. RFC 4231
//! vectors are asserted in the tests below; `cargo test` is the gate.

